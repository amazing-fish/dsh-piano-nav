/** Clock-controlled entry/exit and interruption contracts, without a scheduler. */
import assert from 'node:assert/strict'
import { createPointerWave, POINTER_WAVE_DURATION_MS as duration } from '../src/client/pointer-wave.ts'
const wave = createPointerWave()
const a = { key: 'a', offset: 0 }
wave.point(a, 0)
assert.equal(wave.sample(0).strength, 0, 'entry starts at the current width')
const entry = wave.sample(duration / 3)
assert.ok(entry.strength > 0 && entry.strength < 1)
wave.point({ key: 'b', offset: .25 }, duration / 3)
assert.equal(wave.sample(duration / 3).strength, entry.strength, 'Y changes do not restart amplitude')
assert.equal(wave.sample(duration).strength, 1)
wave.point(null, duration)
const departing = wave.sample(duration * 1.4)
assert.equal(departing.anchor.key, 'b', 'exit retains only a visual anchor')
assert.ok(departing.strength > 0 && departing.strength < 1)
wave.point(a, duration * 1.4)
assert.equal(wave.sample(duration * 1.4).strength, departing.strength, 're-entry begins at the actual amplitude')
assert.ok(wave.sample(duration * 1.6).strength > departing.strength)
wave.point(null, duration * 1.6)
wave.point(null, duration * 2)
assert.deepEqual(wave.sample(duration * 3), { anchor: null, strength: 0, moving: false }, 'outside samples cannot extend a fade indefinitely')
wave.point(a, duration * 4, true)
assert.equal(wave.sample(duration * 4, true).strength, 1)
wave.point(null, duration * 4, true)
assert.deepEqual(wave.sample(duration * 4, true), { anchor: null, strength: 0, moving: false })
wave.point(a, duration * 5)
wave.reset()
assert.deepEqual(wave.sample(duration * 6), { anchor: null, strength: 0, moving: false }, 'ownership changes discard the old envelope')
wave.point(a, duration * 7, false, .7)
assert.equal(wave.sample(duration * 7).strength, .7, 'keyboard-to-pointer acquisition preserves its painted amplitude')
console.log('pointer amplitude: entry, Y continuity, interrupted exit, finite idle, reduced motion and reset passed')
